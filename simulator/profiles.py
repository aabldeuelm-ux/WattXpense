def _base_load_w(minute_of_day: int, weekday: bool, standby_w: float) -> float:
    hour = minute_of_day / 60.0
    load = standby_w
    load += 18.0 * math.exp(-(((hour - 7.4) / 1.3) ** 2))
    load += 12.0 * math.exp(-(((hour - 12.6) / 1.1) ** 2))
    load += 48.0 * math.exp(-(((hour - 19.2) / 2.3) ** 2))
    if weekday and 8.5 <= hour <= 17.6:
        load += 96.0
    if not weekday and 10.0 <= hour <= 20.5:
        load += 22.0
    return load


def _day_curve(
    day: datetime,
    profile: DeviceProfile,
    rng: random.Random,
    extra_loads: Sequence[tuple[int, int, float]] = (),
) -> list[float]:
    weekday = day.weekday() < 5
    curve = [_base_load_w(minute, weekday, profile.standby_w) for minute in range(MINUTES_PER_DAY)]

    slow_walk = 0.0
    for minute in range(MINUTES_PER_DAY):
        slow_walk = slow_walk * 0.985 + rng.gauss(0.0, 0.32)
        curve[minute] += slow_walk
        curve[minute] += rng.gauss(0.0, max(profile.standby_w * 0.035, 0.8))

    for activity in profile.activities:
        if not activity.enabled or day.weekday() not in activity.weekdays:
            continue
        if rng.random() > activity.probability:
            continue
        start_hour = rng.gauss(activity.start_hour_mean, activity.start_hour_std)
        start_hour = min(max(start_hour, 0.0), 23.5)
        start_minute = int(start_hour * 60)
        duration = int(rng.uniform(*activity.duration_minutes))
        watts = rng.uniform(*activity.power_w)
        for offset in range(duration):
            index = start_minute + offset
            if 0 <= index < MINUTES_PER_DAY:
                curve[index] += watts

    for start_minute, duration, watts in extra_loads:
        for offset in range(duration):
            index = start_minute + offset
            if 0 <= index < MINUTES_PER_DAY:
                curve[index] += watts

    return [max(value, 0.5) for value in curve]


@dataclass
class InjectedAnomaly:
    day: str
    kind: str
    description: str
    start_minute: int
    duration_minutes: int
    power_w: float


def plan_injected_anomalies(
    start_day: datetime,
    days: int,
    rng: random.Random,
) -> list[InjectedAnomaly]:
    if days < 12:
        return []

    candidates = list(range(max(days - 10, 2), days - 1))
    rng.shuffle(candidates)
    chosen = candidates[:3]
    plans: list[InjectedAnomaly] = []

    specs = (
        ("space heater left running overnight", 60 + rng.randrange(0, 120), 180, 1850.0),
        ("extra heater or dryer run in the evening", 19 * 60 + rng.randrange(0, 90), 200, 2150.0),
        ("second high-draw evening block", 20 * 60 + rng.randrange(0, 60), 150, 1600.0),
    )
    for index, offset in enumerate(chosen):
        kind, start_minute, duration, watts = specs[index % len(specs)]
        day = start_day + timedelta(days=offset)
        plans.append(
            InjectedAnomaly(
                day=day.date().isoformat(),
                kind=kind,
                description=f"{kind} for {duration} minutes",
                start_minute=start_minute,
                duration_minutes=duration,
                power_w=watts,
            )
        )
    return plans


def generate_readings(
    profile: DeviceProfile,
    start: datetime,
    end: datetime,
    *,
    seed: int = 20260926,
    anomalies: Sequence[InjectedAnomaly] = (),
    gaps: Sequence[str] = (),
) -> list[ReadingSample]:
    rng = random.Random(seed)
    start = start.astimezone(timezone.utc)
    end = end.astimezone(timezone.utc)
    gap_days = set(gaps)

    by_day: dict[str, list[InjectedAnomaly]] = {}
    for anomaly in anomalies:
        by_day.setdefault(anomaly.day, []).append(anomaly)

    samples: list[ReadingSample] = []
    day = start.replace(hour=0, minute=0, second=0, microsecond=0)
    step = timedelta(minutes=profile.interval_minutes)
    steps_per_day = MINUTES_PER_DAY // profile.interval_minutes

    while day < end:
        day_key = day.date().isoformat()
        if day_key in gap_days:
            day += timedelta(days=1)
            continue

        extra = [
            (item.start_minute, item.duration_minutes, item.power_w) for item in by_day.get(day_key, [])
        ]
        curve = _day_curve(day, profile, rng, extra)

        for step_index in range(steps_per_day):
            ts = day + step * step_index
            if ts < start or ts >= end:
                continue
            minute_of_day = step_index * profile.interval_minutes
            power_w = curve[minute_of_day]

            sag = min(7.0, power_w / 600.0)
            voltage = profile.nominal_voltage_v - sag + rng.gauss(0.0, 1.6)
            voltage = round(max(voltage, 170.0), 2)

            power_factor = 1.0
            if power_w > 300:
                power_factor = rng.uniform(0.92, 0.995)
            current = round(power_w / (voltage * power_factor), 4) if voltage > 0 else 0.0
            energy_wh = round(power_w * profile.interval_hours, 4)

            samples.append(
                ReadingSample(
                    device_id=profile.device_id,
                    ts=ts,
                    voltage=voltage,
                    current=current,
                    power_w=round(power_w, 2),
                    energy_wh=energy_wh,
                    source=SOURCE_LABEL,
                    is_simulated=True,
                )
            )
        day += timedelta(days=1)

    return samples


def describe_simulator(profiles: Iterable[DeviceProfile], anomalies: Sequence[InjectedAnomaly]) -> dict:
    return {
        "source": SOURCE_LABEL,
        "is_simulated": True,
        "interface": "POST /api/readings (the same endpoint used for real hardware)",
        "devices": [
            {
                "device_id": profile.device_id,
                "name": profile.name,
                "location": profile.location,
                "interval_minutes": profile.interval_minutes,
                "is_primary": profile.is_primary,
                "standby_w": profile.standby_w,
                "activity_models": [a.name for a in profile.activities if a.enabled],
            }
            for profile in profiles
        ],
        "injected_anomalies": [
            {"day": a.day, "kind": a.kind, "description": a.description} for a in anomalies
        ],
    }
