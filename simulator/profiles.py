@dataclass(frozen=True)
class Activity:
    name: str
    weekdays: tuple[int, ...]
    start_hour_mean: float
    start_hour_std: float
    duration_minutes: tuple[float, float]
    power_w: tuple[float, float]
    probability: float
    power_factor: tuple[float, float] = (0.94, 1.0)
    enabled: bool = True


@dataclass(frozen=True)
class DeviceProfile:
    device_id: str
    name: str
    location: str
    interval_minutes: int
    standby_w: float
    nominal_voltage_v: float
    is_primary: bool = False
    activities: tuple[Activity, ...] = ()
    notes: str = "Simulated circuit. No physical hardware is attached."

    @property
    def interval_hours(self) -> float:
        return self.interval_minutes / 60.0


